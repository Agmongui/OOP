#pragma once

#include <string>
#include <stdexcept>

using namespace std;

/**
 * @brief Представляет тип банковского счета
 * Счет может быть одного из двух типов
 * - дебетовый
 * - накопительный
 * Для накопительного счета при каждом пополнении
 * начисляется процент от внесенной суммы
 */
class AccountType
{
private:
    /**
     * @brief Признак накопительного счета
     * true — накопительный счет
     * false — дебетовый счет
     */
    bool savings;

    /**
     * @brief Процентная ставка по счету (в процентах)
     * Для дебетового счета равна 0
     * Для накопительного счета по умолчанию равна 3
     * Используется при пополнении накопительного счета
     */
    double procent_stavka;

public:
    /**
     * @brief Проверяет, является ли счет накопительным
     * @return true, если счет накопительный
     * @return false, если счет дебетовый
     */
    bool isSavings() const;

    /**
     * @brief Создает объект типа AccountType
     * @param isSavings Признак накопительного счета
     * true — накопительный счет, false — дебетовый счет
     * @param rate Процентная ставка (по умолчанию 3.0)
     * @note По умолчанию создается дебетовый счет
     * Для дебетового счета ставка принудительно равна 0
     */
    AccountType(bool isSavings = false, double rate = 3.0);

    /**
     * @brief Возвращает процентную ставку по счету
     * @return Процентная ставка (например, 3.0 означает 3%)
     */
    double getProcentStavka() const;

    /**
     * @brief Возвращает название типа банковского счета
     * @return Строка "Накопительный" для накопительного счета
     * или "Дебетовый" для дебетового счета
     */
    string toString() const;
};

/**
 * @brief Представляет банковский счет
 *
 * Класс хранит информацию о банковском счете
 * номер счета, имя владельца, баланс, валюту,
 * статус и тип счета
 */
class BankAccount
{
private:
    /**
     * @brief Номер банковского счета
     *
     * Номер должен быть больше нуля
     */
    long long accountNumber;

    /**
     * @brief Имя владельца банковского счета
     * Имя не должно быть пустым
     */
    string ownerName;

    /**
     * @brief Текущий баланс банковского счета
     * Баланс не может быть отрицательным
     */
    double balance;

    /**
     * @brief Статус банковского счета
     * true — счет активен
     * false — счет заблокирован
     */
    bool active;

    /**
     * @brief Валюта банковского счета
     * Валюта не должна быть пустой строкой
     */
    string currency;

    /**
     * @brief Тип банковского счета
     * Определяет, является ли счет дебетовым
     * или накопительным
     */
    AccountType type;

    /**
     * @brief Количество существующих объектов BankAccount
     * Увеличивается при создании объекта BankAccount
     * и уменьшается при его уничтожении
     */
    static int objectCount;

    /**
     * @brief Проверяет корректность номера счета
     * @param number Номер банковского счета
     * @throw invalid_argument Если номер счета меньше
     * или равен нулю
     */
    void validateAccountNumber(long long number) const;

    /**
     * @brief Проверяет корректность имени владельца
     * @param owner Имя владельца банковского счета
     * @throw invalid_argument Если имя владельца пустое
     */
    void validateOwnerName(const string& owner) const;

    /**
     * @brief Проверяет корректность начального баланса
     * @param balance Баланс банковского счета
     * @throw invalid_argument Если баланс отрицательный
     */
    void validateBalance(double balance) const;

public:
    /**
     * @brief Создает банковский счет по умолчанию
     */
    BankAccount();

    /**
     * @brief Создает банковский счет с заданными параметрами
     *
     * @param number Номер банковского счета
     * @param owner Имя владельца счета
     * @param initialBalance Начальный баланс
     * @param accountCurrency Валюта счета
     * @param accountType Тип банковского счета
     *
     * @throw invalid_argument Если номер счета некорректен
     * имя владельца пустое
     * баланс отрицательный
     * или валюта пустая
     *
     * @note Создаваемый счет является активным
     */
    BankAccount(
        long long number,
        const string& owner,
        double initialBalance,
        const string& accountCurrency,
        const AccountType& accountType);

    /**
     * @brief Создает дебетовый банковский счет
     * @param number Номер банковского счета
     * @param owner Имя владельца счета
     * @throw invalid_argument Если номер счета меньше
     * или равен нулю либо имя владельца пустое
     */
    BankAccount(
        long long number,
        const string& owner);

    /**
     * @brief Уничтожает объект банковского счета
     *
     * При уничтожении объекта счетчик objectCount
     * уменьшается на единицу
     */
    ~BankAccount();

    /**
     * @brief Возвращает количество существующих объектов BankAccount
     * @return Текущее количество объектов класса BankAccount
     */
    static int getObjectCount();

    /**
     * @brief Возвращает номер банковского счета
     * @return Номер банковского счета
     */
    long long getAccountNumber() const;

    /**
     * @brief Возвращает имя владельца банковского счета
     * @return Имя владельца счета
     */
    string getOwnerName() const;

    /**
     * @brief Возвращает текущий баланс банковского счета
     * @return Текущий баланс счета
     */
    double getBalance() const;

    /**
     * @brief Возвращает статус банковского счета
     * @return true, если счет активен
     * @return false, если счет заблокирован
     */
    bool isActive() const;

    /**
     * @brief Возвращает валюту банковского счета
     * @return Валюта счета
     */
    string getCurrency() const;

    /**
     * @brief Возвращает тип банковского счета
     * @return Объект AccountType, описывающий тип счета
     */
    AccountType getType() const;

    /**
     * @brief Пополняет банковский счет
     * Сначала проверяется активность счета
     * и корректность суммы пополнения
     *
     * Для дебетового счета внесенная сумма
     * просто добавляется к балансу
     *
     * Для накопительного счета дополнительно начисляется
     * процент от внесенной суммы, хранящийся в типе счета
     *
     * @param amount Сумма пополнения счета
     * @throw runtime_error Если счет заблокирован
     * @throw invalid_argument Если сумма пополнения
     * меньше или равна нулю
     * @note Для накопительного счета процент
     * начисляются именно от суммы текущего пополнения
     */
    void deposit(double amount);

    /**
     * @brief Снимает деньги с банковского счета
     *
     * С дебетового счета деньги можно снять
     * если запрашиваемая сумма не превышает текущий баланс
     *
     * Накопительный счет не позволяет снимать деньги
     *
     * @param amount Сумма, которую необходимо снять
     *
     * @return true, если деньги успешно сняты
     * @return false, если на счете недостаточно средств
     *
     * @throw runtime_error Если счет заблокирован
     * или является накопительным
     *
     * @throw invalid_argument Если сумма снятия
     * меньше или равна нулю
     *
     * @note Баланс изменяется только при успешном снятии
     */
    bool withdraw(double amount);

    /**
     * @brief Блокирует банковский счет
     * После блокировки операции пополнения и снятия
     * денежных средств становятся недоступными
     */
    void block();

    /**
     * @brief Разблокирует банковский счет
     * После разблокировки счет снова становится активным
     */
    void unblock();

    /**
     * @brief Выводит информацию о банковском счете
     */
    void print() const;
};